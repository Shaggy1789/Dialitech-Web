const DEFAULT_LOCALE = 'es';

const savedLocale = (() => {
  try {
    const stored = localStorage.getItem('appearance_preferences');
    if (stored) {
      const parsed = JSON.parse(stored);
      if (parsed?.language && messages[parsed.language]) return parsed.language;
    }
  } catch {
    /* ignore */
  }
  return DEFAULT_LOCALE;
})();

const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: savedLocale,
  fallbackLocale: 'es',
  messages,
});

export function setLocale(locale) {
  if (messages[locale]) {
    i18n.global.locale.value = locale;
    localStorage.setItem('appearance_preferences', JSON.stringify({
      ...JSON.parse(localStorage.getItem('appearance_preferences') || '{}'),
      language: locale,
    }));
    document.documentElement.setAttribute('lang', locale === 'es' ? 'es' : 'en');
  }
}

export function getLocale() {
  return i18n.global.locale.value;
}

export function $t(key, params) {
  return i18n.global.t(key, params);
}

export function t(key, params) {
  return $t(key, params);
}

export function useI18n() {
  const { t: vueT, locale } = i18n.global;
  return {
    locale,
    setLocale,
    t: (key, params) => vueT(key, params),
  };
}

export default i18n;
